#!/usr/bin/env node
/**
 * Regenerate `docs/PERMISSION_MATRIX.md` from the table the tests run.
 *
 * Prose about permissions drifts from behaviour, and the drift is invisible: the document
 * still reads correctly, it is just no longer true. Generating it from
 * `packages/authz/src/__tests__/matrix.ts` and `resources.ts` — the same data the suite
 * executes — removes the possibility, and `release-check` fails when the file is stale.
 *
 *   node scripts/generate-permission-matrix.mjs           regenerate
 *   node scripts/generate-permission-matrix.mjs --check   fail if stale
 */

import { readFileSync, writeFileSync } from 'node:fs';
import process from 'node:process';

import * as prettier from 'prettier';

const { NAMED_CASES, SCOPE_LEVELS, SUBJECT_KINDS_UNDER_TEST, ROLES_UNDER_TEST } =
  await import('../packages/authz/src/__tests__/matrix.ts');
const { liveResources, pendingResources } =
  await import('../packages/authz/src/__tests__/resources.ts');

const OUTPUT = 'docs/PERMISSION_MATRIX.md';

const SUBJECT_LABELS = {
  member: 'Member',
  sync_token: 'Sync token',
  share_link: 'Share link',
  anonymous: 'Anonymous',
};

const LEVEL_LABELS = {
  none: '—',
  ancestorFolder: 'Ancestor folder',
  folder: 'Folder',
  project: 'Project',
  song: 'Song',
};

const yesNo = (value) => (value ? 'yes' : 'no');
const roleLabel = (role) => role ?? '**none**';

function namedTable() {
  const header =
    '| Case | Subject | Granted | Denied at | Workspace role | → Role | → Download |\n' +
    '| --- | --- | --- | --- | --- | --- | --- |';

  const rows = NAMED_CASES.map(
    (c) =>
      `| ${c.name} | ${SUBJECT_LABELS[c.subjectKind]} | ${c.given} | ` +
      `${LEVEL_LABELS[c.denyLevel]} | ${c.membershipRole ?? '—'} | ` +
      `${roleLabel(c.expectedRole)} | ${yesNo(c.expectedDownload)} |`,
  );

  return `${header}\n${rows.join('\n')}`;
}

function reasonsList() {
  return NAMED_CASES.map((c) => `- **${c.name}** — ${c.because}`).join('\n');
}

function resourceTable() {
  const header = '| Resource class | Status | Why it is sensitive |\n| --- | --- | --- |';
  const live = liveResources.map((r) => `| \`${r.name}\` | covered | ${r.why} |`);
  const pending = pendingResources.map((r) => `| \`${r.name}\` | task \`${r.task}\` | ${r.why} |`);
  return `${header}\n${[...live, ...pending].join('\n')}`;
}

const document = `# You & Friends — Permission Matrix

_A private music workspace by Avery and Friends._

> **Generated by \`scripts/generate-permission-matrix.mjs\` from the table the tests execute.**
> Do not hand-edit. \`release-check\` fails if this file is stale.
>
> The source is \`packages/authz/src/__tests__/matrix.ts\` and \`resources.ts\`. Every row below
> is a test case that runs on every build, so this document cannot describe behaviour the
> system does not have.

## 1. The rules

Permissions may be granted at **folder**, **project**, or **song** level and inherit downward
(\`docs/DESIGN.md\` §3). Four rules decide every question:

1. **Most specific wins.** The grant nearest the target decides — including when it grants
   *less*. Narrowing one song to viewer under a folder-wide editor grant is a thing owners do,
   and "highest role wins" would ignore them.
2. **A deny overrides what is less specific than itself.** A deny on the song beats an allow
   on the folder. An allow on the song beats a deny on the folder. Read the direction
   carefully; both are tested.
3. **Capabilities resolve independently of role.** \`canDownload\` and \`canInvite\` each walk the
   chain separately. A viewer permitted to download and an editor refused it are both legal.
   A grant that is silent about a capability does not revoke it.
4. **Deny by default.** No grant and no membership is no access. A resource class nobody has
   wired up is unreachable rather than accidentally public (ADR 0006).

Roles, in order: ${ROLES_UNDER_TEST.map((r) => `\`${r}\``).join(' → ')}.

Scope depths swept by the matrix: ${SCOPE_LEVELS.map((l) => `\`${l}\``).join(', ')}.

Subject kinds: ${SUBJECT_KINDS_UNDER_TEST.map((s) => `\`${s}\``).join(', ')}. Only a **member**
inherits the workspace baseline — a share-link bearer or a sync token holding one would turn
every shared song into an invitation (\`docs/THREAT_MODEL.md\` T5).

## 2. Worked cases

${namedTable()}

### Why each case exists

${reasonsList()}

## 3. The full sweep

Beyond the cases above, the suite enumerates every combination of role × scope depth × deny
level × subject kind (${ROLES_UNDER_TEST.length} × ${SCOPE_LEVELS.length} × ${SCOPE_LEVELS.length + 1} × ${SUBJECT_KINDS_UNDER_TEST.length} = ${ROLES_UNDER_TEST.length * SCOPE_LEVELS.length * (SCOPE_LEVELS.length + 1) * SUBJECT_KINDS_UNDER_TEST.length} cases), plus all
16 combinations of the two capabilities against every role, and the membership baseline
against every subject kind.

Expectations for the sweep come from a **one-line rule stated independently of the resolver** —
*a deny wins if and only if it sits at or above the winning grant's level* — because a test
that derives its expected answer from the algorithm under test proves only that the algorithm
is deterministic.

## 4. Cross-workspace access

Every tenant-owned resource class carries a cross-workspace test asserting that a request
naming another tenant's id is answered **404-shaped**: the public code, the HTTP status, and
the message are all identical to a genuine not-found. A 403 would confirm the resource exists,
which is the disclosure \`docs/THREAT_MODEL.md\` T1 is about.

The suite reads the live database and fails if a tenant-owned table is not in this list, so a
new resource class cannot ship without its case.

${resourceTable()}

_Generated from the executable matrix. Last regenerated by \`pnpm generate:permission-matrix\`._
`;

const formatted = await prettier.format(document, { parser: 'markdown' });

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUTPUT, 'utf8');
  } catch {
    console.error(`${OUTPUT} does not exist. Run: pnpm generate:permission-matrix`);
    process.exit(1);
  }

  if (current !== formatted) {
    console.error(
      `${OUTPUT} is stale — the permission rules changed without the document following.\n` +
        'Run: pnpm generate:permission-matrix',
    );
    process.exit(1);
  }

  console.log(`${OUTPUT} is current.`);
} else {
  writeFileSync(OUTPUT, formatted);
  console.log(`${OUTPUT} regenerated.`);
}
